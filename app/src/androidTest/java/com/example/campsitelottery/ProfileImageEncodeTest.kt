package com.example.campsitelottery

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.media.ExifInterface
import android.net.Uri
import android.util.Base64
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File

/**
 * Code and documentation generated by Claude (Anthropic, Claude Opus 5.5). Estimated AI-generated share of this file: ~100%
 * Runs [encodeProfileImage] on real image files: size, cropping, EXIF rotation and bad input.
 */
@RunWith(AndroidJUnit4::class)
class ProfileImageEncodeTest {

    private val context = InstrumentationRegistry.getInstrumentation().targetContext

    /** Saves a [width] x [height] JPEG whose left half is red and right half blue. */
    private fun splitImage(width: Int, height: Int, orientation: Int = ExifInterface.ORIENTATION_NORMAL): Uri {
        val bitmap = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
        Canvas(bitmap).apply {
            drawRect(0f, 0f, width / 2f, height.toFloat(), Paint().apply { color = Color.RED })
            drawRect(width / 2f, 0f, width.toFloat(), height.toFloat(), Paint().apply { color = Color.BLUE })
        }
        val file = File.createTempFile("profile", ".jpg", context.cacheDir)
        file.outputStream().use { bitmap.compress(Bitmap.CompressFormat.JPEG, 95, it) }
        if (orientation != ExifInterface.ORIENTATION_NORMAL) {
            ExifInterface(file.absolutePath).apply {
                setAttribute(ExifInterface.TAG_ORIENTATION, orientation.toString())
                saveAttributes()
            }
        }
        return Uri.fromFile(file)
    }

    /**
     * Saves a square JPEG with four coloured quarters: red top-left, green top-right,
     * blue bottom-left, yellow bottom-right, tagged with the EXIF [orientation].
     */
    private fun quarters(orientation: Int): Uri {
        val size = 400
        val bitmap = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
        val half = size / 2f
        Canvas(bitmap).apply {
            drawRect(0f, 0f, half, half, Paint().apply { color = Color.RED })
            drawRect(half, 0f, size.toFloat(), half, Paint().apply { color = Color.GREEN })
            drawRect(0f, half, half, size.toFloat(), Paint().apply { color = Color.BLUE })
            drawRect(half, half, size.toFloat(), size.toFloat(), Paint().apply { color = Color.YELLOW })
        }
        val file = File.createTempFile("quarters", ".jpg", context.cacheDir)
        file.outputStream().use { bitmap.compress(Bitmap.CompressFormat.JPEG, 95, it) }
        ExifInterface(file.absolutePath).apply {
            setAttribute(ExifInterface.TAG_ORIENTATION, orientation.toString())
            saveAttributes()
        }
        return Uri.fromFile(file)
    }

    /** Names the colour of each quarter of [bitmap]: top-left, top-right, bottom-left, bottom-right. */
    private fun quarterColors(bitmap: Bitmap): List<String> {
        val q = bitmap.width / 4
        return listOf(q to q, 3 * q to q, q to 3 * q, 3 * q to 3 * q).map { (x, y) ->
            val p = bitmap.getPixel(x, y)
            val (r, g, b) = Triple(Color.red(p) > 150, Color.green(p) > 150, Color.blue(p) > 150)
            when {
                r && g && !b -> "yellow"
                r -> "red"
                g -> "green"
                b -> "blue"
                else -> "?"
            }
        }
    }

    @Test
    fun allEightExifOrientationsComeOutUpright() = runBlocking {
        // Each EXIF value says how the stored pixels must be transformed to show the
        // photo upright; these are the quarters a correct viewer would display.
        val expected = mapOf(
            ExifInterface.ORIENTATION_NORMAL to listOf("red", "green", "blue", "yellow"),
            ExifInterface.ORIENTATION_FLIP_HORIZONTAL to listOf("green", "red", "yellow", "blue"),
            ExifInterface.ORIENTATION_ROTATE_180 to listOf("yellow", "blue", "green", "red"),
            ExifInterface.ORIENTATION_FLIP_VERTICAL to listOf("blue", "yellow", "red", "green"),
            ExifInterface.ORIENTATION_TRANSPOSE to listOf("red", "blue", "green", "yellow"),
            ExifInterface.ORIENTATION_ROTATE_90 to listOf("blue", "red", "yellow", "green"),
            ExifInterface.ORIENTATION_TRANSVERSE to listOf("yellow", "green", "blue", "red"),
            ExifInterface.ORIENTATION_ROTATE_270 to listOf("green", "yellow", "red", "blue"),
        )
        for ((orientation, quarters) in expected) {
            val bitmap = decode(encodeProfileImage(context, quarters(orientation))!!)
            assertEquals("orientation $orientation", quarters, quarterColors(bitmap))
        }
    }

    @Test
    fun aVeryLongPanoramaIsHandled() = runBlocking {
        // 16000 x 400 is 6.4 MP, above the decode cap.
        val encoded = encodeProfileImage(context, splitImage(16_000, 400))
        assertNotNull(encoded)
        assertEquals(ProfileImagePolicy.SIZE_PX, decode(encoded!!).width)
    }

    private fun decode(encoded: String): Bitmap {
        val bytes = Base64.decode(encoded, Base64.DEFAULT)
        return BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
    }

    private fun isRed(pixel: Int) = Color.red(pixel) > 180 && Color.blue(pixel) < 80
    private fun isBlue(pixel: Int) = Color.blue(pixel) > 180 && Color.red(pixel) < 80

    @Test
    fun aLargePhotoBecomesASmallSquare() = runBlocking {
        val encoded = encodeProfileImage(context, splitImage(3000, 2000))
        assertNotNull(encoded)
        val bytes = Base64.decode(encoded, Base64.DEFAULT)
        assertTrue("stored picture is ${bytes.size} bytes", bytes.size <= ProfileImagePolicy.MAX_BYTES)
        val bitmap = decode(encoded!!)
        assertEquals(ProfileImagePolicy.SIZE_PX, bitmap.width)
        assertEquals(ProfileImagePolicy.SIZE_PX, bitmap.height)
    }

    @Test
    fun theCropIsCentred() = runBlocking {
        // A wide image keeps its middle, so the square is half red, half blue.
        val bitmap = decode(encodeProfileImage(context, splitImage(800, 400))!!)
        assertTrue(isRed(bitmap.getPixel(40, 128)))
        assertTrue(isBlue(bitmap.getPixel(216, 128)))
    }

    @Test
    fun exifRotationIsApplied() = runBlocking {
        // Rotated 90° clockwise, the red left half ends up on top.
        val bitmap = decode(encodeProfileImage(context, splitImage(800, 400, ExifInterface.ORIENTATION_ROTATE_90))!!)
        assertTrue(isRed(bitmap.getPixel(128, 40)))
        assertTrue(isBlue(bitmap.getPixel(128, 216)))
    }

    @Test
    fun aFileThatIsNotAnImageIsRejected() = runBlocking {
        val file = File.createTempFile("notimage", ".jpg", context.cacheDir).apply { writeText("hello") }
        assertNull(encodeProfileImage(context, Uri.fromFile(file)))
    }

    @Test
    fun aMissingFileIsRejected() = runBlocking {
        assertNull(encodeProfileImage(context, Uri.fromFile(File(context.cacheDir, "missing.jpg"))))
    }

    @Test
    fun anOversizedStoredPictureIsShrunkForDisplay() {
        // A picture written some other way, much bigger than this app would save.
        val big = Bitmap.createBitmap(3000, 2000, Bitmap.Config.ARGB_8888).apply { eraseColor(Color.GREEN) }
        val out = java.io.ByteArrayOutputStream()
        big.compress(Bitmap.CompressFormat.JPEG, 80, out)
        val shown = decodeProfileImage(Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP))!!
        assertTrue("shown at ${shown.width} x ${shown.height}", maxOf(shown.width, shown.height) <= ProfileImagePolicy.MAX_DISPLAY_PX)
    }

    @Test
    fun theStoredPictureDecodesForDisplay() = runBlocking {
        val encoded = encodeProfileImage(context, splitImage(500, 500))
        assertNotNull(decodeProfileImage(encoded))
        assertNotNull(decodeProfileImage("data:image/jpeg;base64,$encoded"))
        assertNull(decodeProfileImage("not an image"))
        assertNull(decodeProfileImage(null))
    }
}
