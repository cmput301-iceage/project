@RunWith(AndroidJUnit4::class)
class AdminImagesScreenTest {

    @get:Rule
    val composeRule = createComposeRule()

    private val picture = jpeg(Color.RED)
    private val site = Campsite(campsiteId = "site1", ownerId = "owner1", name = "Lakeside Pines", imageUrl = jpeg(Color.GREEN))
    private val alice = ProfileImageEntry("alice", "Alice Moreau", picture)

    private fun jpeg(color: Int): String {
        val bitmap = Bitmap.createBitmap(64, 64, Bitmap.Config.ARGB_8888).apply { eraseColor(color) }
        val out = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, 80, out)
        return Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP)
    }

    private fun repo(profiles: List<ProfileImageEntry> = listOf(alice)) =
        InMemoryAdminImageRepository(listOf(site), profiles, mapOf("owner1" to "Olive Owner"))

    /** Holds back profile pictures until [release] is called, like a slow Firestore query. */
    private class HeldProfiles(private val inner: InMemoryAdminImageRepository) : AdminImageRepository by inner {
        private var pending: (() -> Unit)? = null
        override fun listenToProfileImages(
            onUpdate: (List<ProfileImageEntry>) -> Unit,
            onError: (Exception) -> Unit,
        ): () -> Unit {
            var stop: () -> Unit = {}
            pending = { stop = inner.listenToProfileImages(onUpdate, onError) }
            return { stop() }
        }
        fun release() = pending!!.invoke()
    }

    private fun show(repo: AdminImageRepository) {
        composeRule.setContent { AdminImagesScreen(rememberNavController(), repo) }
    }

    @Test
    fun showsProfilePictureAlongsideCampsiteImage() {
        show(repo())
        composeRule.onNodeWithTag("imageCard_site1").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        composeRule.onNodeWithText("Profile: Alice Moreau").assertIsDisplayed()
        composeRule.onNodeWithContentDescription("Profile picture of Alice Moreau").assertIsDisplayed()
    }

    @Test
    fun removesProfilePictureAfterConfirming() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.onNodeWithText("Are you sure you want to delete Alice Moreau's profile picture?").assertIsDisplayed()
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()

        composeRule.onNodeWithTag("imageActionMessage").assertTextContains("Removed Alice Moreau's profile picture.")
        composeRule.onNodeWithTag("profileImageCard_alice").assertDoesNotExist()
        assertTrue(repo.storedProfiles().isEmpty())
        assertEquals(site.imageUrl, repo.storedCampsites().single().imageUrl)
    }

    @Test
    fun cancellingKeepsProfilePicture() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.onNodeWithTag("cancelDeleteImageButton").performClick()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        assertEquals(1, repo.storedProfiles().size)
    }

    @Test
    fun pictureChangedWhileConfirmingIsNotRemoved() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.runOnIdle { repo.putProfile(alice.copy(image = jpeg(Color.BLUE))) }
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()

        composeRule.onNodeWithTag("imageErrorMessage").assertTextContains(AdminImageMessages.PICTURE_CHANGED)
        composeRule.onNodeWithTag("confirmDeleteImageButton").assertDoesNotExist()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        assertEquals(1, repo.storedProfiles().size)
    }

    @Test
    fun removingCampsiteImageStillWorks() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteImageButton_site1").performClick()
        composeRule.onNodeWithText("Are you sure you want to delete this image for \"Lakeside Pines\"?").assertIsDisplayed()
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()

        composeRule.onNodeWithTag("imageActionMessage").assertTextContains("Removed image from Lakeside Pines.")
        composeRule.onNodeWithTag("imageCard_site1").assertDoesNotExist()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        assertEquals(1, repo.storedProfiles().size)
    }

    @Test
    fun campsiteImagesShowWhileProfilePicturesAreStillLoading() {
        val held = HeldProfiles(repo())
        show(held)
        composeRule.onNodeWithTag("imageCard_site1").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImagesLoading").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImageCard_alice").assertDoesNotExist()

        composeRule.runOnIdle { held.release() }
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImagesLoading").assertDoesNotExist()
    }

    @Test
    fun spinnerNotEmptyMessageWhileOnlyProfilePicturesAreLoading() {
        val held = HeldProfiles(InMemoryAdminImageRepository(profiles = listOf(alice)))
        show(held)
        composeRule.onNodeWithTag("emptyImagesMessage").assertDoesNotExist()
        composeRule.runOnIdle { held.release() }
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
    }

    @Test
    fun removalErrorSurvivesLaterCampsiteUpdate() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.runOnIdle { repo.putProfile(alice.copy(image = jpeg(Color.BLUE))) }
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()
        composeRule.runOnIdle { repo.putCampsite(site.copy(name = "Lakeside Pines (renamed)")) }

        composeRule.onNodeWithText("Campsite: Lakeside Pines (renamed)").assertIsDisplayed()
        composeRule.onNodeWithTag("imageErrorMessage").assertTextContains(AdminImageMessages.PICTURE_CHANGED)
    }

    @Test
    fun filterShowsOnlyProfilePictures() {
        show(repo())
        composeRule.onNodeWithTag("imageCard_site1").assertIsDisplayed()
        composeRule.onNodeWithTag("imageFilterButton").performClick()
        composeRule.onNodeWithTag("imageFilter_PROFILES").performClick()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        composeRule.onNodeWithTag("imageCard_site1").assertDoesNotExist()
    }

    @Test
    fun searchFindsProfileByUserName() {
        show(repo(listOf(alice, ProfileImageEntry("zed", "Zed Albers", picture))))
        composeRule.onNodeWithTag("adminImagesList").performScrollToNode(hasTestTag("profileImageCard_zed"))
        composeRule.onNodeWithTag("imageSearchField").performTextInput("moreau")
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImageCard_zed").assertDoesNotExist()
        composeRule.onNodeWithTag("imageCard_site1").assertDoesNotExist()
    }

    @Test
    fun unreadablePictureCanStillBeRemoved() {
        val repo = repo(listOf(alice.copy(image = "not a real picture, just text that is long enough")))
        show(repo)
        composeRule.onNodeWithText("This picture can't be displayed.").assertIsDisplayed()
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()
        composeRule.onNodeWithTag("profileImageCard_alice").assertDoesNotExist()
    }

    @Test
    fun profileLoadErrorIsShownWithoutHidingCampsiteImages() {
        val failing = object : AdminImageRepository by repo() {
            override fun listenToProfileImages(
                onUpdate: (List<ProfileImageEntry>) -> Unit,
                onError: (Exception) -> Unit,
            ): () -> Unit {
                onError(IllegalStateException("permission denied"))
                return {}
            }
        }
        show(failing)
        composeRule.onNodeWithTag("profileImagesError")
            .assertTextContains("Couldn't load profile pictures: permission denied")
        composeRule.onNodeWithTag("imageCard_site1").assertIsDisplayed()
    }
}
