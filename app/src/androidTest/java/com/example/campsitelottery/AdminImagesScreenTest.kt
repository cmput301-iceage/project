@RunWith(AndroidJUnit4::class)
class AdminImagesScreenTest {

    @get:Rule
    val composeRule = createComposeRule()

    private val picture = jpeg(Color.RED)
    private val site = Campsite(campsiteId = "site1", ownerId = "owner1", name = "Lakeside Pines", imageUrl = jpeg(Color.GREEN))
    private val alice = ProfileImageEntry("alice", "Alice Moreau", picture)

    private fun jpeg(color: Int): String {
        val bitmap = Bitmap.createBitmap(64, 64, Bitmap.Config.ARGB_8888).apply { eraseColor(color) }
        val out = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, 80, out)
        return Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP)
    }

    private fun repo(profiles: List<ProfileImageEntry> = listOf(alice)) =
        InMemoryAdminImageRepository(listOf(site), profiles, mapOf("owner1" to "Olive Owner"))

    /** Holds back one kind of image until [release] is called, like a slow Firestore query. */
    private class Held(
        private val inner: InMemoryAdminImageRepository,
        private val holdCampsites: Boolean = false,
    ) : AdminImageRepository by inner {
        private var pending: (() -> Unit)? = null
        private var stop: () -> Unit = {}
        private var registered = false

        private fun hold(start: () -> (() -> Unit)): () -> Unit {
            check(!registered) { "Held only supports one listener" }
            registered = true
            pending = { stop = start() }
            return {
                pending = null
                stop()
            }
        }

        override fun listenToCampsites(onUpdate: (List<Campsite>) -> Unit, onError: (Exception) -> Unit) =
            if (holdCampsites) hold { inner.listenToCampsites(onUpdate, onError) }
            else inner.listenToCampsites(onUpdate, onError)

        override fun listenToProfileImages(
            onUpdate: (List<ProfileImageEntry>) -> Unit,
            onError: (Exception) -> Unit,
        ) = if (holdCampsites) inner.listenToProfileImages(onUpdate, onError)
            else hold { inner.listenToProfileImages(onUpdate, onError) }

        /** Delivers the held images once; later calls do nothing. */
        fun release() {
            val start = pending ?: return
            pending = null
            start()
        }
    }

    /** Where the row with [key] is in the whole list, composed or not; -1 if it isn't in the list. */
    private fun listIndexOf(key: String): Int =
        composeRule.onNodeWithTag("adminImagesList").fetchSemanticsNode()
            .config[SemanticsProperties.IndexForKey](key)

    private fun show(repo: AdminImageRepository) {
        composeRule.setContent { AdminImagesScreen(rememberNavController(), repo) }
    }

    @Test
    fun showsProfilePictureAlongsideCampsiteImage() {
        show(repo())
        composeRule.onNodeWithTag("imageCard_site1").assertIsDisplayed()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        composeRule.onNodeWithText("Profile: Alice Moreau").assertIsDisplayed()
        composeRule.onNodeWithContentDescription("Profile picture of Alice Moreau").assertIsDisplayed()
    }

    @Test
    fun removesProfilePictureAfterConfirming() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.onNodeWithText("Are you sure you want to delete Alice Moreau's profile picture?").assertIsDisplayed()
        composeRule.onNodeWithTag("confirmDeleteImageButton").performClick()

        composeRule.onNodeWithTag("imageActionMessage").assertTextContains("Removed Alice Moreau's profile picture.")
        composeRule.onNodeWithTag("profileImageCard_alice").assertDoesNotExist()
        assertTrue(repo.storedProfiles().isEmpty())
        assertEquals(site.imageUrl, repo.storedCampsites().single().imageUrl)
    }

    @Test
    fun cancellingKeepsProfilePicture() {
        val repo = repo()
        show(repo)
        composeRule.onNodeWithTag("deleteProfileImageButton_alice").performClick()
        composeRule.onNodeWithTag("cancelDeleteImageButton").performClick()
        composeRule.onNodeWithTag("profileImageCard_alice").assertIsDisplayed()
        assertEquals(1, repo.storedProfiles().size)
    }

    @Test
