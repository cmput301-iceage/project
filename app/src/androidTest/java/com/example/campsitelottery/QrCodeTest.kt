package com.example.campsitelottery

import androidx.compose.material3.Text
import androidx.compose.ui.test.assertIsDisplayed
import androidx.compose.ui.test.assertIsEnabled
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.navigation.compose.NavHost
import androidx.navigation.compose.composable
import androidx.navigation.compose.rememberNavController
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Code and documentation generated by Claude (Anthropic, Claude Opus 5.5). Estimated AI-generated share of this file: ~100%
 * UI tests for showing a campsite's QR code and scanning one from the home screen,
 * using a fake scanner so no camera is needed.
 */
@RunWith(AndroidJUnit4::class)
class QrCodeTest {

    @get:Rule
    val composeRule = createComposeRule()

    /** Pretends to scan [result]; null pretends the user closed the scanner. */
    private class FakeQrScanner(private val result: String?) : QrScanner {
        override fun scan(onScanned: (String) -> Unit, onCancelled: () -> Unit, onFailure: (Exception) -> Unit) {
            if (result == null) onCancelled() else onScanned(result)
        }
    }

    private fun showHome(scanner: QrScanner) {
        val user = User(userId = "device-1", name = "Jane")
        composeRule.setContent {
            val navController = rememberNavController()
            NavHost(navController = navController, startDestination = "home") {
                composable("home") {
                    HomeScreen(
                        navController,
                        userState = UserState.Ready(user),
                        userRepository = InMemoryUserRepository(listOf(user)),
                        qrScanner = scanner,
                    )
                }
                composable("campsiteInfo/{campsiteId}") { entry ->
                    Text("Opened ${entry.arguments?.getString("campsiteId")}")
                }
            }
        }
    }

    @Test
    fun qrDialogShowsTheCodeAndCloses() {
        var closed = false
        composeRule.setContent {
            CampsiteQrDialog(campsiteId = "campsite_01", campsiteName = "Pine Ridge Retreat", onDismiss = { closed = true })
        }
        composeRule.onNodeWithTag("qrCodeImage").assertIsDisplayed()
        composeRule.onNodeWithText("Pine Ridge Retreat").assertIsDisplayed()
        composeRule.onNodeWithTag("closeQrButton").performClick()
        assertTrue(closed)
    }

    @Test
    fun qrDialogOffersToSaveTheImage() {
        composeRule.setContent {
            CampsiteQrDialog(campsiteId = "campsite_01", campsiteName = "Pine Ridge Retreat", onDismiss = {})
        }
        composeRule.onNodeWithTag("saveQrButton").assertIsDisplayed().assertIsEnabled()
    }

    @Test
    fun scanningACampsiteCodeOpensTheCampsite() {
        showHome(FakeQrScanner(CampsiteQrCode.linkFor("campsite_01")))
        composeRule.onNodeWithTag("scanQrButton").performClick()
        composeRule.onNodeWithText("Opened campsite_01").assertIsDisplayed()
    }

    @Test
    fun scanningAnotherCodeShowsAnError() {
        showHome(FakeQrScanner("https://example.com"))
        composeRule.onNodeWithTag("scanQrButton").performClick()
        composeRule.onNodeWithTag("qrErrorText").assertIsDisplayed()
    }

    @Test
    fun closingTheScannerDoesNothing() {
        showHome(FakeQrScanner(null))
        composeRule.onNodeWithTag("scanQrButton").performClick()
        composeRule.onNodeWithTag("qrErrorText").assertDoesNotExist()
        composeRule.onNodeWithTag("scanQrButton").assertIsDisplayed()
    }
}
