 * UI tests for [AdminCampsiteReviewsScreen], using an in-memory repository.
 */
@RunWith(AndroidJUnit4::class)
class AdminCampsiteReviewsScreenTest {

    @get:Rule
    val composeRule = createComposeRule()

    private val site = Campsite(campsiteId = "site1", ownerId = "owner", name = "Lakeside Pines")

    private fun repo() = InMemoryReviewRepository(
        listOf(site),
        mapOf(
            "site1" to listOf(
                Review("spammer", "Spam Bot", "BUY CHEAP WATCHES", Date(2)),
                Review("fan", "Sam", "Lovely and quiet.", Date(1)),
            )
        ),
    )

    private fun showScreen(
        repo: ReviewRepository,
        loadCampsite: (String, (Campsite?) -> Unit) -> Unit = { _, onResult -> onResult(site) },
    ) {
        composeRule.setContent {
            AdminCampsiteReviewsScreen(
                rememberNavController(),
                campsiteId = "site1",
                reviewRepository = repo,
                loadCampsite = loadCampsite,
            )
        }
    }

    private fun reviewers(repo: ReviewRepository): List<String> {
        var result: List<Review>? = null
        repo.getReviews("site1", onSuccess = { result = it }, onFailure = { throw it })
        return result!!.map { it.userId }
    }

    @Test
    fun listsEveryReviewWithAuthorAndText() {
        showScreen(repo())
        composeRule.onNodeWithTag("adminReviewsCampsiteName").assertTextEquals("Lakeside Pines")
        composeRule.onNodeWithText("Spam Bot").assertExists()
        composeRule.onNodeWithTag("adminReviewText_spammer").assertTextEquals("BUY CHEAP WATCHES")
        composeRule.onNodeWithTag("adminReviewText_fan").assertTextEquals("Lovely and quiet.")
    }

    @Test
    fun removingAfterConfirmDeletesTheReview() {
        val repo = repo()
        showScreen(repo)
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()

        composeRule.onNodeWithTag("adminReview_spammer").assertDoesNotExist()
        composeRule.onNodeWithTag("adminReview_fan").assertExists()
        composeRule.onNodeWithTag("adminReviewsMessage").assertTextEquals("Removed Spam Bot's review.")
        assertEquals(listOf("fan"), reviewers(repo))
    }

    @Test
    fun cancellingKeepsTheReview() {
        val repo = repo()
        showScreen(repo)
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithText("Cancel").performClick()

        composeRule.onNodeWithTag("adminReview_spammer").assertExists()
        assertEquals(listOf("spammer", "fan"), reviewers(repo))
    }

    @Test
    fun removingTheLastReviewShowsEmptyState() {
        val repo = InMemoryReviewRepository(
            listOf(site),
            mapOf("site1" to listOf(Review("spammer", "Spam Bot", "Spam", Date()))),
        )
        showScreen(repo)
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()

        composeRule.onNodeWithTag("noReviewsText").assertExists()
    }

    @Test
    fun editedReviewIsNotRemovedAndListReloads() {
        val repo = repo()
        showScreen(repo)
        // The author edits their review after the admin's list loaded.
        repo.submitReview("site1", "spammer", "Spam Bot", "Sorry, edited.", {}, { throw it })
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()

        composeRule.onNodeWithTag("adminReviewsError").assertTextEquals(ReviewPolicy.CHANGED_MESSAGE)
        composeRule.onNodeWithTag("adminReviewText_spammer").assertTextEquals("Sorry, edited.")
        assertEquals(listOf("spammer", "fan"), reviewers(repo))
    }

    @Test
    fun failedRemovalShowsError() {
        val repo = repo()
        showScreen(repo)
        repo.failWith = IllegalStateException("offline")
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()

        composeRule.onNodeWithTag("adminReviewsError").assertTextEquals("offline")
    }

    @Test
    fun loadFailureOffersRetry() {
        val repo = repo().apply { failWith = IllegalStateException("offline") }
        showScreen(repo)
        composeRule.onNodeWithTag("retryReviewsButton").assertExists()
        repo.failWith = null
        composeRule.onNodeWithTag("retryReviewsButton").performClick()
        composeRule.onNodeWithTag("adminReview_fan").assertExists()
    }

    @Test
    fun reviewsCanBeRemovedEvenIfTheCampsiteFailsToLoad() {
        val repo = repo()
        showScreen(repo, loadCampsite = { _, onResult -> onResult(null) })
        composeRule.onNodeWithTag("adminReviewsCampsiteName").assertDoesNotExist()
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()
        assertEquals(listOf("fan"), reviewers(repo))
    }

    @Test
    fun otherRemoveButtonsAreDisabledWhileRemoving() {
        // A repository whose removal never finishes, to hold the screen mid-removal.
        val inner = repo()
        val stalled = object : ReviewRepository by inner {
            override fun removeReview(
                campsiteId: String,
                userId: String,
                expected: Review?,
                onSuccess: () -> Unit,
                onFailure: (Exception) -> Unit,
            ) = Unit
        }
        showScreen(stalled)
        composeRule.onNodeWithTag("removeReview_spammer").performClick()
        composeRule.onNodeWithTag("confirmRemoveReviewButton").performClick()
        composeRule.onNodeWithTag("removeReview_fan").assertIsNotEnabled()
    }
}
