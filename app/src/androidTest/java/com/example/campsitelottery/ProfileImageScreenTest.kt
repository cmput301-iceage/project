package com.example.campsitelottery

import android.graphics.Bitmap
import android.graphics.Color
import android.util.Base64
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.test.assertIsNotEnabled
import androidx.compose.ui.test.assertTextEquals
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.navigation.compose.rememberNavController
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import java.io.ByteArrayOutputStream

/**
 * Code and documentation generated by Claude (Anthropic, Claude Opus 5.5). Estimated AI-generated share of this file: ~100%
 * UI tests for adding, changing and removing a profile picture on [ProfileScreen],
 * with a fake photo chooser and an in-memory repository.
 */
@RunWith(AndroidJUnit4::class)
class ProfileImageScreenTest {

    @get:Rule
    val composeRule = createComposeRule()

    /** A tiny real JPEG of one colour, Base64 encoded like a stored profile picture. */
    private fun solidImage(color: Int): String {
        val bitmap = Bitmap.createBitmap(8, 8, Bitmap.Config.ARGB_8888).apply { eraseColor(color) }
        val out = ByteArrayOutputStream()
        bitmap.compress(Bitmap.CompressFormat.JPEG, 90, out)
        return Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP)
    }

    /** A chooser that "picks" whatever [next] holds; null means the photo couldn't be used. */
    private class FakeChooser : ProfileImageChooser {
        var next: String? = null
        var cancel = false
        var hold = false
        override fun choose(onPicked: () -> Unit, onResult: (String?) -> Unit) {
            if (cancel) return
            onPicked()
            if (!hold) onResult(next)
        }
    }

    private lateinit var repo: InMemoryUserRepository
    private val chooser = FakeChooser()

    private fun showProfile(user: User) {
        repo = InMemoryUserRepository(listOf(user))
        composeRule.setContent {
            // Stands in for the app's user state, which onUserChanged updates.
            var current by remember { mutableStateOf(user) }
            ProfileScreen(
                navController = rememberNavController(),
                userState = UserState.Ready(current),
                userRepository = repo,
                onUserChanged = { change -> current = change(current) },
                onUserDeleted = {},
                chooseImage = chooser,
            )
        }
    }

    @Test
    fun withoutAPhotoShowsTheInitialAndAddPhoto() {
        showProfile(User(userId = "u1", name = "jane"))
        composeRule.onNodeWithTag("profileImagePlaceholder").assertExists()
        composeRule.onNodeWithText("J").assertExists()
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Add Photo")
        composeRule.onNodeWithTag("removePhotoButton").assertDoesNotExist()
    }

    @Test
    fun addingAPhotoSavesAndShowsIt() {
        showProfile(User(userId = "u1", name = "Jane"))
        val image = solidImage(Color.RED)
        chooser.next = image
        composeRule.onNodeWithTag("choosePhotoButton").performClick()

        composeRule.onNodeWithTag("profileImage").assertExists()
        composeRule.onNodeWithTag("profileImagePlaceholder").assertDoesNotExist()
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Change Photo")
        composeRule.onNodeWithTag("removePhotoButton").assertExists()
        assertEquals(image, repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun changingAPhotoReplacesIt() {
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = solidImage(Color.RED)))
        val blue = solidImage(Color.BLUE)
        chooser.next = blue
        composeRule.onNodeWithTag("choosePhotoButton").performClick()
        assertEquals(blue, repo.peek("u1")?.profileImageUrl)
        composeRule.onNodeWithTag("profileImage").assertExists()
    }

    @Test
    fun removingAfterConfirmGoesBackToTheInitial() {
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = solidImage(Color.RED)))
        composeRule.onNodeWithTag("removePhotoButton").performClick()
        composeRule.onNodeWithTag("confirmRemovePhotoButton").performClick()

        composeRule.onNodeWithTag("profileImagePlaceholder").assertExists()
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Add Photo")
        assertNull(repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun cancellingRemovalKeepsThePhoto() {
        val image = solidImage(Color.RED)
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = image))
        composeRule.onNodeWithTag("removePhotoButton").performClick()
        composeRule.onNodeWithTag("cancelRemovePhotoButton").performClick()

        composeRule.onNodeWithTag("profileImage").assertExists()
        assertEquals(image, repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun backingOutOfThePickerChangesNothing() {
        showProfile(User(userId = "u1", name = "Jane"))
        chooser.cancel = true
        composeRule.onNodeWithTag("choosePhotoButton").performClick()
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Add Photo")
        composeRule.onNodeWithTag("photoErrorText").assertDoesNotExist()
        assertNull(repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun anUnusablePhotoShowsAnError() {
        showProfile(User(userId = "u1", name = "Jane"))
        chooser.next = null
        composeRule.onNodeWithTag("choosePhotoButton").performClick()
        composeRule.onNodeWithTag("photoErrorText").assertTextEquals("Couldn't use that photo. Try a different one.")
        assertNull(repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun aFailedSaveShowsAnErrorAndKeepsTheOldPhoto() {
        val old = solidImage(Color.RED)
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = old))
        repo.failWith = IllegalStateException("offline")
        chooser.next = solidImage(Color.BLUE)
        composeRule.onNodeWithTag("choosePhotoButton").performClick()

        composeRule.onNodeWithTag("photoErrorText").assertTextEquals("Couldn't save your photo: offline")
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Change Photo")
        assertEquals(old, repo.peek("u1")?.profileImageUrl)
    }

    @Test
    fun buttonsAreDisabledWhileAPhotoIsProcessed() {
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = solidImage(Color.RED)))
        chooser.hold = true
        composeRule.onNodeWithTag("choosePhotoButton").performClick()
        composeRule.onNodeWithTag("choosePhotoButton").assertTextEquals("Processing...")
        composeRule.onNodeWithTag("choosePhotoButton").assertIsNotEnabled()
        composeRule.onNodeWithTag("removePhotoButton").assertIsNotEnabled()
    }

    @Test
    fun aCorruptStoredPhotoFallsBackToTheInitialAndCanBeRemoved() {
        showProfile(User(userId = "u1", name = "Jane", profileImageUrl = "not an image"))
        composeRule.onNodeWithTag("profileImagePlaceholder").assertExists()
        composeRule.onNodeWithTag("removePhotoButton").performClick()
        composeRule.onNodeWithTag("confirmRemovePhotoButton").performClick()
        assertNull(repo.peek("u1")?.profileImageUrl)
    }
}
