 * Checks that the admin dashboard's bell opens the notification log, the only way into it.
 */
@RunWith(AndroidJUnit4::class)
class AdminDashboardNotificationsTest {

    @get:Rule
    val composeRule = createComposeRule()

    @Test
    fun bellOpensTheNotificationLog() {
        val admin = User(userId = "admin", name = "Admin", isAdmin = true)
        composeRule.setContent {
            val navController = rememberNavController()
            NavHost(navController, startDestination = "adminDashboard") {
                composable("adminDashboard") {
                    AdminDashboardScreen(
                        navController,
                        userState = UserState.Ready(admin),
                        userRepository = remember { InMemoryUserRepository(listOf(admin)) },
                    )
                }
                // Stand-in for the real log screen, which reads Firestore.
                composable("adminNotifications") { Text("Notification log") }
            }
        }

        composeRule.onNodeWithTag("toNotificationsButton").performClick()
        composeRule.onNodeWithText("Notification log").assertExists()
    }
}
