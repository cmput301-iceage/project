package com.example.campsitelottery

import androidx.compose.ui.test.assertIsEnabled
import androidx.compose.ui.test.assertIsNotEnabled
import androidx.compose.ui.test.assertTextContains
import androidx.compose.ui.test.assertTextEquals
import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onNodeWithTag
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.performTextInput
import androidx.compose.ui.test.performTextReplacement
import androidx.navigation.compose.rememberNavController
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Assert.assertEquals
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import java.util.Date

/**
 * Documentation generated by Claude
 * UI tests for [PostReviewDialog] and [CampsiteReviewsScreen], using an in-memory repository.
 */
@RunWith(AndroidJUnit4::class)
class CampsiteReviewsScreenTest {

    @get:Rule
    val composeRule = createComposeRule()

    private val site = Campsite(campsiteId = "site1", ownerId = "owner", name = "Lakeside Pines")

    private fun showScreen(deviceId: String, repo: InMemoryReviewRepository = InMemoryReviewRepository(listOf(site))) {
        composeRule.setContent {
            CampsiteReviewsScreen(
                rememberNavController(),
                campsiteId = "site1",
                deviceId = deviceId,
                authorName = "Jane",
                reviewRepository = repo,
                loadCampsite = { _, onResult -> onResult(site) },
            )
        }
    }

    @Test
    fun postIsDisabledUntilTextIsEntered() {
        composeRule.setContent { PostReviewDialog(initialText = null, onSubmit = {}, onDismiss = {}) }
        composeRule.onNodeWithTag("submitReviewButton").assertIsNotEnabled()
        composeRule.onNodeWithTag("reviewTextField").performTextInput("   ")
        composeRule.onNodeWithTag("submitReviewButton").assertIsNotEnabled()
        composeRule.onNodeWithTag("reviewTextField").performTextInput("Nice")
        composeRule.onNodeWithTag("submitReviewButton").assertIsEnabled()
    }

    @Test
    fun postIsDisabledWhenTooLong() {
        composeRule.setContent { PostReviewDialog(initialText = null, onSubmit = {}, onDismiss = {}) }
        composeRule.onNodeWithTag("reviewTextField").performTextReplacement("a".repeat(ReviewPolicy.MAX_LENGTH + 1))
        composeRule.onNodeWithTag("submitReviewButton").assertIsNotEnabled()
        composeRule.onNodeWithTag("reviewLengthText")
            .assertTextEquals("${ReviewPolicy.MAX_LENGTH + 1} / ${ReviewPolicy.MAX_LENGTH}")
    }

    @Test
    fun postSendsTrimmedText() {
        var submitted: String? = null
        composeRule.setContent { PostReviewDialog(initialText = null, onSubmit = { submitted = it }, onDismiss = {}) }
        composeRule.onNodeWithTag("reviewTextField").performTextInput("  Great stay  ")
        composeRule.onNodeWithTag("submitReviewButton").performClick()
        assertEquals("Great stay", submitted)
    }

    @Test
    fun emptyCampsiteInvitesFirstReview() {
        showScreen(deviceId = "guest")
        composeRule.onNodeWithTag("noReviewsText").assertTextEquals("No reviews yet. Be the first to write one!")
        composeRule.onNodeWithTag("writeReviewButton").assertTextEquals("Write a Review")
    }

    @Test
    fun postingAReviewShowsItInTheList() {
        showScreen(deviceId = "guest")
        composeRule.onNodeWithTag("writeReviewButton").performClick()
        composeRule.onNodeWithTag("reviewTextField").performTextInput("Quiet and clean")
        composeRule.onNodeWithTag("submitReviewButton").performClick()

        composeRule.onNodeWithText("Quiet and clean").assertExists()
        composeRule.onNodeWithText("Jane (you)").assertExists()
        composeRule.onNodeWithTag("reviewMessageText").assertTextEquals("Thanks! Your review was posted.")
        composeRule.onNodeWithTag("writeReviewButton").assertTextEquals("Edit My Review")
    }

    @Test
    fun editingPrefillsAndReplacesTheReview() {
        val repo = InMemoryReviewRepository(
            listOf(site),
            mapOf("site1" to listOf(Review("guest", "Jane", "Old text", Date()))),
        )
        showScreen(deviceId = "guest", repo = repo)
        composeRule.onNodeWithTag("writeReviewButton").performClick()
        composeRule.onNodeWithTag("reviewTextField").assertTextContains("Old text")
        composeRule.onNodeWithTag("reviewTextField").performTextReplacement("New text")
        composeRule.onNodeWithTag("submitReviewButton").performClick()

        composeRule.onNodeWithText("New text").assertExists()
        composeRule.onNodeWithText("Old text").assertDoesNotExist()
        composeRule.onNodeWithTag("reviewMessageText").assertTextEquals("Your review was updated.")
    }

    @Test
    fun ownerSeesReviewsButCannotWriteOne() {
        val repo = InMemoryReviewRepository(
            listOf(site),
            mapOf("site1" to listOf(Review("guest", "Sam", "Loved it", Date()))),
        )
        showScreen(deviceId = "owner", repo = repo)
        composeRule.onNodeWithText("Loved it").assertExists()
        composeRule.onNodeWithTag("writeReviewButton").assertDoesNotExist()
    }

    @Test
    fun loadFailureOffersRetry() {
        val repo = InMemoryReviewRepository(listOf(site)).apply { failWith = IllegalStateException("offline") }
        showScreen(deviceId = "guest", repo = repo)
        composeRule.onNodeWithTag("retryReviewsButton").assertExists()
        composeRule.onNodeWithTag("writeReviewButton").assertIsNotEnabled()

        repo.failWith = null
        composeRule.onNodeWithTag("retryReviewsButton").performClick()
        composeRule.onNodeWithTag("noReviewsText").assertExists()
    }
}
